export function sdnT(locale, key, vars) {
    const table = SDN_I18N[locale] || SDN_I18N.en;
    let s = table[key] ?? SDN_I18N.en[key] ?? key;
    if (vars && typeof vars === 'object') {
        for (const [k, v] of Object.entries(vars)) {
            s = s.replaceAll(`{${k}}`, String(v ?? ''));
        }
    }
    return s;
}
