/**
 * @param {'en'|'ar'|string} locale
 * @param {string} key
 * @param {Record<string, string|number>} [vars]
 */
export function mktPromoT(locale, key, vars) {
  const pack = MKT_PROMO_I18N[locale] || MKT_PROMO_I18N.en;
  let text = pack[key] ?? MKT_PROMO_I18N.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

/**
 * @param {'en'|'ar'|string} locale
 * @param {string} status
 */
export function mktPromoStatusLabel(locale, status) {
  const value = String(status || '')
    .trim()
    .toLowerCase()
    .replace(/\s+/g, '_');
  const key = `status.${value}`;
  const label = mktPromoT(locale, key);
  return label === key ? String(status || '') : label;
}

/**
 * @param {'en'|'ar'|string} locale
 * @param {string} value English option value stored in form/API mapping
 */
export function mktPromoOptionLabel(locale, value) {
  const key = OPTION_LABEL_KEYS[value];
  if (!key) return String(value || '');
  return mktPromoT(locale, key);
}

/**
 * @param {'en'|'ar'|string} locale
 * @param {string[]} values
 */
export function mktPromoSelectOptions(locale, values) {
  return values.map((value) => ({
    id: value,
    label: mktPromoOptionLabel(locale, value),
  }));
}

/**
 * Resolve marketing/portal locale from outlet context or localStorage.
 * @param {Record<string, unknown>} [outletCtx]
 */
export function resolveMarketingLocale(outletCtx) {
  return (
    outletCtx?.locale ||
    (typeof localStorage !== 'undefined'
      ? localStorage.getItem('portal-locale')
      : null) ||
    (typeof localStorage !== 'undefined'
      ? localStorage.getItem('marketing-locale')
      : null) ||
    'en'
  );
}
