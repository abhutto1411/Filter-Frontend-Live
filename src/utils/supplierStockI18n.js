/**
 * @param {'en'|'ar'|string} locale
 * @param {string} key
 * @param {Record<string, string|number>} [vars]
 */
export function sstockT(locale, key, vars) {
    const pack = SSTOCK_I18N[locale] || SSTOCK_I18N.en;
    let text = pack[key] ?? SSTOCK_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}
