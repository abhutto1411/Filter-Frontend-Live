/**
 * @param {'en'|'ar'|string} locale
 * @param {string} key
 * @param {Record<string, string|number>} [vars]
 */
export function mktRefT(locale, key, vars) {
  const pack = MKT_REF_I18N[locale] || MKT_REF_I18N.en;
  let text = pack[key] ?? MKT_REF_I18N.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

/**
 * @param {'en'|'ar'|string} locale
 * @param {number|string} value
 */
export function mktRefFormatSar(locale, value) {
  const n = Number(value);
  if (!Number.isFinite(n)) {
    return mktRefT(locale, 'format.sar', { amount: '0.00' });
  }
  return mktRefT(locale, 'format.sar', {
    amount: n.toFixed(2),
  });
}

/**
 * @param {'en'|'ar'|string} locale
 * @param {string} status
 */
export function mktRefStatusLabel(locale, status) {
  const value = String(status || 'active').trim().toLowerCase();
  const key = `status.${value}`;
  const label = mktRefT(locale, key);
  return label === key ? status : label;
}

/**
 * @param {'en'|'ar'|string} locale
 * @param {string} category
 */
export function mktRefCategoryLabel(locale, category) {
  const raw = String(category || 'Individual').trim();
  const key = `cat.${raw.toLowerCase()}`;
  const label = mktRefT(locale, key);
  return label === key ? raw : label;
}
