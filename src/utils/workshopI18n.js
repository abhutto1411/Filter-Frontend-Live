export function wsT(locale, key, vars) {
    const pack = WS_I18N[locale] || WS_I18N.en;
    let text = pack[key] ?? WS_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}

