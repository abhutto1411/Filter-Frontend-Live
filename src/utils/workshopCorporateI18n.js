export function wcorpT(locale, key, vars) {
    const pack = WCORP_I18N[locale] || WCORP_I18N.en;
    let text = pack[key] ?? WCORP_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}
