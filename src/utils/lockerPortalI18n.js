/**
 * @param {'en'|'ar'|string} locale
 * @param {string} key
 * @param {Record<string, string|number>} [vars]
 */
export function lockerT(locale, key, vars) {
    const pack = LOCKER_PORTAL_I18N[locale] || LOCKER_PORTAL_I18N.en;
    let text = pack[key] ?? LOCKER_PORTAL_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}
