export function wiT(locale, key, vars) {
    const pack = WI_I18N[locale] || WI_I18N.en;
    let text = pack[key] ?? WI_I18N.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
    return text;
}

