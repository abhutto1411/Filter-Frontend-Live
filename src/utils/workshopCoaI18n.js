const BADGE_LABEL_KEYS = {
    Control: 'badge.control',
    BNPL: 'badge.bnpl',
    SoftPOS: 'badge.softpos',
    Marketing: 'badge.marketing',
    Advances: 'badge.advances',
    Referral: 'badge.referral',
    Promotions: 'badge.promotions',
};

export function coaT(locale, key, vars) {
    const pack = COA_I18N[locale] || COA_I18N.en;
    let text = pack[key] ?? COA_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}

export function coaTypeLabel(locale, type) {
    return coaT(locale, `type.${type}`) || type;
}

export function coaBadgeLabel(locale, englishLabel) {
    const key = BADGE_LABEL_KEYS[englishLabel];
    return key ? coaT(locale, key) : englishLabel;
}
