export function expLogT(locale, key, vars) {
    const pack = EXP_LOG_I18N[locale] || EXP_LOG_I18N.en;
    let text = pack[key] ?? EXP_LOG_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}
