export function accT(locale, key, vars) {
    const pack = ACC_I18N[locale] || ACC_I18N.en;
    let text = pack[key] ?? ACC_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}

