export function arT(locale, key, vars = {}) {
    const lang = locale === 'ar' ? 'ar' : 'en';
    let text = AR_I18N[lang][key] ?? AR_I18N.en[key] ?? key;
    Object.entries(vars).forEach(([k, v]) => {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v ?? ''));
    });
    return text;
}
