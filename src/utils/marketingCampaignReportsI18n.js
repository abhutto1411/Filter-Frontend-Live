/**
 * @param {'en'|'ar'|string} locale
 * @param {string} key
 * @param {Record<string, string|number>} [vars]
 */
export function mktCampReportT(locale, key, vars) {
  const pack = MKT_CAMP_REPORTS_I18N[locale] || MKT_CAMP_REPORTS_I18N.en;
  let text = pack[key] ?? MKT_CAMP_REPORTS_I18N.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

/**
 * @param {'en'|'ar'|string} locale
 * @param {number|string} value
 */
export function mktCampReportMoney(locale, value) {
  const n = Number(value);
  const amount = (Number.isFinite(n) ? n : 0).toLocaleString(undefined, {
    maximumFractionDigits: 0,
  });
  return mktCampReportT(locale, 'money.sar', { amount });
}

/**
 * @param {'en'|'ar'|string} locale
 * @param {number|string} value
 * @param {number} [digits]
 */
export function mktCampReportPercent(locale, value, digits = 2) {
  const n = Number(value);
  const raw = Number.isFinite(n) ? n : 0;
  const formatted = Number(raw).toLocaleString(undefined, {
    maximumFractionDigits: digits,
  });
  return mktCampReportT(locale, 'percent', { value: formatted });
}
