export function empT(locale, key, vars) {
    const pack = EMP_I18N[locale] || EMP_I18N.en;
    let text = pack[key] ?? EMP_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}

