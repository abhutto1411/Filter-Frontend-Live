/**
 * @param {'en'|'ar'|string} locale
 * @param {string} key
 * @param {Record<string, string|number>} [vars]
 */
export function apT(locale, key, vars) {
    const pack = AP_I18N[locale] || AP_I18N.en;
    let text = pack[key] ?? AP_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}

export function entityTypeLabel(locale, value) {
    const key = `entity.${value ?? ''}`;
    return apT(locale, key);
}
