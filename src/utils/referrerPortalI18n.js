export function rfT(locale, key, vars) {
  const pack = RF_I18N[locale] || RF_I18N.en;
  let text = pack[key] ?? RF_I18N.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function rfStatusKey(status) {
  const raw = String(status || '').toLowerCase();
  if (raw === 'converted') return 'status.converted';
  if (raw === 'pending') return 'status.pending';
  if (raw === 'rejected') return 'status.rejected';
  if (raw === 'paid') return 'status.paid';
  if (raw === 'approved') return 'status.approved';
  return null;
}
