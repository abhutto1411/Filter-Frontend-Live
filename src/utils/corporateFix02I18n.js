export function cfx02T(locale, key, vars) {
    const pack = String(locale || '').startsWith('ar') ? CFX02_I18N.ar : CFX02_I18N.en;
    let text = pack[key] ?? CFX02_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
    }
    return text;
}

/** Running-balance settlement statement rows (1340 view: Dr bill, Cr payouts). */
export function buildSettlementStatementRows(bills, locale) {
    const events = [];
    for (const b of bills || []) {
        for (const e of b.events || []) events.push({ ...e, billNo: b.billNo });
    }
    events.sort((a, b) => String(a.date || '').localeCompare(String(b.date || '')));
    let bal = 0;
    return events.map((e) => {
        const dr = Number(e.debit || 0);
        const cr = Number(e.credit || 0);
        bal = Math.round((bal + dr - cr) * 100) / 100;
        return {
            date: e.date || '',
            description: cfx02T(locale, `stmt.kind.${e.kind}`, { ref: e.ref || e.billNo || '' }),
            debit: dr,
            credit: cr,
            balance: bal,
        };
    });
}
