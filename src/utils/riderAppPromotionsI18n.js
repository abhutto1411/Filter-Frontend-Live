export function riderAppT(locale, key, vars) {
  const lang = locale === 'ar' ? 'ar' : 'en';
  let text = RIDER_APP_I18N[lang][key] ?? RIDER_APP_I18N.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`{{${k}}}`, 'g'), String(v));
    }
  }
  return text;
}
