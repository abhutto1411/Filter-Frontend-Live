export function spiT(locale, key, vars) {
    const pack = SPI_I18N[locale] || SPI_I18N.en;
    let text = pack[key] ?? SPI_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}
