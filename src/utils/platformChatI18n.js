/**
 * @param {'en'|'ar'|string} locale
 * @param {string} key
 * @param {Record<string, string|number>} [vars]
 */
export function pcT(locale, key, vars) {
    const pack = PLATFORM_CHAT_I18N[locale] || PLATFORM_CHAT_I18N.en;
    let text = pack[key] ?? PLATFORM_CHAT_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}
