export function salesT(locale, key, vars) {
    const pack = SALES_I18N[locale] || SALES_I18N.en;
    let text = pack[key] ?? SALES_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}

