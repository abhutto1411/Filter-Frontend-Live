/**
 * @param {'en'|'ar'|string} locale
 * @param {string} key
 * @param {Record<string, string|number>} [vars]
 */
export function permT(locale, key, vars) {
    const pack = PERM_I18N[locale] || PERM_I18N.en;
    let text = pack[key] ?? PERM_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}

export function actionLabel(locale, action) {
    const key = `action.${action}`;
    const text = permT(locale, key);
    return text === key ? action : text;
}

export function portalLabel(locale, portalId) {
    return permT(locale, `portal.${portalId}`);
}

export function portalDesc(locale, portalId) {
    return permT(locale, `portal.${portalId}.desc`);
}

export function workshopRoleLabel(locale, roleId) {
    return permT(locale, `wsRole.${roleId}`);
}

export function portalLoginHintT(locale, portal) {
    const key = `hint.${portal}`;
    const text = permT(locale, key);
    return text === key ? '' : text;
}
