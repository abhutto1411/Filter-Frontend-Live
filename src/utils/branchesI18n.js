export function brT(locale, key, vars) {
    const pack = BR_I18N[locale] || BR_I18N.en;
    let text = pack[key] ?? BR_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}

