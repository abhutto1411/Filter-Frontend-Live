export function aiTrainingT(locale, key, vars = {}) {
  const loc = locale === 'ar' ? 'ar' : 'en';
  let text = AI_TRAINING_I18N[loc][key] ?? AI_TRAINING_I18N.en[key] ?? key;
  Object.entries(vars).forEach(([k, v]) => {
    text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  });
  return text;
}
