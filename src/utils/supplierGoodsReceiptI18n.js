/**
 * Portal languages are EN and AR only. Any other locale (e.g. 'ur', 'hi') has no pack here and
 * falls back to EN: `PACK[locale] || PACK.en`, then per key `pack[key] ?? en[key] ?? key`.
 */
/**
 * MZ-11 — message for an API error from the GR ↔ bill matching. The backend sends English text
 * (with document numbers); a known `code` gets the translated text in Arabic.
 */
export function grApiErrorMessage(locale, error, fallback) {
    if (error?.code === 'GR_ZERO_COST_PRICED_BILL_LINE' && locale === 'ar') {
        return grT(locale, 'link.err.zeroCostPriced');
    }
    return error?.message || fallback;
}

export function grT(locale, key, vars) {
    const pack = GR_I18N[locale] || GR_I18N.en;
    let text = pack[key] ?? GR_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}
