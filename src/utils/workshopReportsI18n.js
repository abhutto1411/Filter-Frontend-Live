function humanizeColKey(key) {
    return String(key || '')
        .replace(/_/g, ' ')
        .replace(/([a-z])([A-Z])/g, '$1 $2')
        .replace(/\b\w/g, (m) => m.toUpperCase());
}

/**
 * @param {'en'|'ar'|string} locale
 * @param {string} key
 * @param {Record<string, string|number>} [vars]
 */
export function wrT(locale, key, vars) {
    const pack = WR_I18N[locale] || WR_I18N.en;
    let text = pack[key] ?? WR_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}

/** Translate a details-table column key when known; otherwise humanize. */
export function wrColT(locale, key) {
    const norm = String(key || '')
        .replace(/([a-z])([A-Z])/g, '$1_$2')
        .replace(/-/g, '_')
        .toLowerCase();
    const pack = WR_I18N[locale] || WR_I18N.en;
    const k = `col.${norm}`;
    return pack[k] ?? WR_I18N.en[k] ?? humanizeColKey(key);
}
