export function rcT(locale, key, vars) {
    const pack = RECEIPTS_I18N[locale] || RECEIPTS_I18N.en;
    let text = pack[key] ?? RECEIPTS_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}
