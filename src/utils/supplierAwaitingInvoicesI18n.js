export function sawT(locale, key, vars) {
    let s = (locale === 'ar' ? ar : en)[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
}
