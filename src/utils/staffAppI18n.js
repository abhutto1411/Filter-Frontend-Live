export function staffAppT(locale, key, vars) {
    const pack = STAFF_APP_I18N[locale] || STAFF_APP_I18N.en;
    let text = pack[key] ?? STAFF_APP_I18N.en[key] ?? key;
    if (vars) {
        for (const [k, v] of Object.entries(vars)) {
            text = text.replaceAll(`{${k}}`, String(v));
        }
    }
    return text;
}

export function staffAppStatusLabel(locale, status) {
    if (status == null || status === '') return staffAppT(locale, 'common.emdash');
    const key = `status.${String(status).toLowerCase().replace(/\s+/g, '_')}`;
    const translated = staffAppT(locale, key);
    return translated === key ? String(status) : translated;
}

export function resolveStaffAppLocale(localeProp, outletLocale) {
    return (
        localeProp ||
        outletLocale ||
        (typeof localStorage !== 'undefined' ? localStorage.getItem('portal-locale') : null) ||
        'en'
    );
}

